import { readdirSync, readFileSync } from 'node:fs';
import { join } from 'node:path';
function snapshot(root: string): Record<string, string> {
  const result: Record<string, string> = {};
  function visit(path: string) {
    for (const item of readdirSync(path, { withFileTypes: true })) {
      const name = join(path, item.name);
      if (item.isDirectory()) visit(name);
      else result[name] = readFileSync(name, 'utf8');
    }
  }
  visit(root);
  return result;
}
const before = { ...snapshot('frontend/Generated'), ...snapshot('backend/OpenAPI') };
const child = Bun.spawn(['bun', 'run', 'generate'], { stdout: 'inherit', stderr: 'inherit' });
if (await child.exited) throw Error('OpenAPI/client generation failed');
const after = { ...snapshot('frontend/Generated'), ...snapshot('backend/OpenAPI') };
if (JSON.stringify(before) !== JSON.stringify(after))
  throw Error('Generated contract/client drift: regenerate and review changes');
const spec = Bun.YAML.parse(readFileSync('backend/OpenAPI/openapi.yaml', 'utf8')) as {
  paths: Record<string, Record<string, any>>;
};
const ids = new Set<string>();
for (const [path, methods] of Object.entries(spec.paths) as [string, Record<string, any>][]) {
  for (const [method, operation] of Object.entries(methods)) {
    if (!operation.operationId || ids.has(operation.operationId))
      throw Error('Missing/duplicate operationId');
    ids.add(operation.operationId);
    if (path.includes('/stays') && method !== 'get')
      throw Error('Stay projection must be read-only');
    if (!operation.responses || !Object.keys(operation.responses).some((s) => s.startsWith('2')))
      throw Error('Success response required');
    if (path !== '/api/health' && !(path === '/api/session' && method === 'post')) {
      if (!operation.security?.some((entry: Record<string, unknown>) => 'cookie' in entry))
        throw Error('Cookie contract missing');
      if (
        ['post', 'patch', 'delete', 'put'].includes(method) &&
        !operation.security.some((entry: Record<string, unknown>) => 'csrf' in entry)
      )
        throw Error('CSRF contract missing');
    }
  }
}
